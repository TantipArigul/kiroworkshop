import { z } from 'zod';

import {
  AGE_BANDS,
  FOCUS_AREAS,
  INPUT_FILE_HEADER,
  INPUT_FILE_MAX_BYTES,
  INPUT_FILE_MAX_ROWS,
  INPUT_FILE_NAME_MAX_LENGTH,
  INPUT_MARKERS,
  LIFESTYLE_FACTORS,
  RUN_NAME_MAX_LENGTH,
  SAMPLE_LABEL_MAX_LENGTH,
} from '../constants.js';
import { jobStatusSchema } from './common.js';
import {
  jobOutputsSummarySchema,
  jobProgressSchema,
  jobRunInfoSchema,
  pipelineIdSchema,
} from './pipelines.js';

const JOB_PAGE_SIZE_MAX = 100;
const SUMMARY_MAX_LENGTH = 256;

export const ageBandSchema = z.enum(AGE_BANDS);
export const focusAreaSchema = z.enum(FOCUS_AREAS);
export const lifestyleFactorSchema = z.enum(LIFESTYLE_FACTORS);
export const inputMarkerNameSchema = z.enum(
  INPUT_MARKERS.map((item) => item.marker) as [
    (typeof INPUT_MARKERS)[number]['marker'],
    ...(typeof INPUT_MARKERS)[number]['marker'][],
  ],
);

/** Cuid identifiers generated by Prisma; anything else is treated as an unknown job. */
export const jobIdSchema = z.string().regex(/^[a-z0-9]{20,40}$/);
export const idempotencyKeySchema = z.uuid();

export const jobParametersSchema = z
  .object({
    sampleLabel: z
      .string()
      .trim()
      .min(1)
      .max(SAMPLE_LABEL_MAX_LENGTH)
      .regex(/^[A-Za-z0-9 _.-]+$/, 'Use letters, numbers, spaces, dots, dashes or underscores.'),
    ageBand: ageBandSchema,
    focusArea: focusAreaSchema,
    lifestyleFactors: z
      .array(lifestyleFactorSchema)
      .max(LIFESTYLE_FACTORS.length)
      .refine((items) => new Set(items).size === items.length, 'Select each factor once.')
      .default([]),
    simulateFailure: z.boolean().default(false),
  })
  .strict();

export const jobInputFileSchema = z
  .object({
    name: z.string().min(1).max(INPUT_FILE_NAME_MAX_LENGTH),
    // Character count is a cheap first bound; the server re-checks the UTF-8 byte size.
    content: z.string().min(1).max(INPUT_FILE_MAX_BYTES),
  })
  .strict();

export const jobSubmitRequestSchema = z
  .object({
    parameters: jobParametersSchema,
    file: jobInputFileSchema,
  })
  .strict();

export const jobListQuerySchema = z
  .object({
    page: z.coerce.number().int().min(1).default(1),
    limit: z.coerce.number().int().min(1).max(JOB_PAGE_SIZE_MAX).default(20),
  })
  .strict();

const isoDateTimeSchema = z.iso.datetime({ offset: true });

export const jobSummarySchema = z
  .object({
    id: jobIdSchema,
    /** Kept for compatibility; equals `runName`. */
    sampleLabel: z.string().max(SAMPLE_LABEL_MAX_LENGTH),
    pipelineId: pipelineIdSchema,
    pipelineName: z.string().min(1).max(128),
    runName: z.string().max(RUN_NAME_MAX_LENGTH),
    status: jobStatusSchema,
    /** 1-based position among QUEUED jobs of the same executor; `null` unless QUEUED. */
    queuePosition: z.number().int().min(1).nullable(),
    progress: jobProgressSchema.nullable(),
    createdAt: isoDateTimeSchema,
    updatedAt: isoDateTimeSchema,
    expiresAt: isoDateTimeSchema,
  })
  .strict();

export const jobStatusHistoryItemSchema = z
  .object({
    status: jobStatusSchema,
    occurredAt: isoDateTimeSchema,
    summary: z.string().max(SUMMARY_MAX_LENGTH).nullable(),
  })
  .strict();

export const jobDetailSchema = jobSummarySchema
  .extend({
    /** Smart Checkup only; `null` for Nextflow runs. */
    parameters: jobParametersSchema.nullable(),
    /** Smart Checkup only; `null` for Nextflow runs. */
    file: z
      .object({
        name: z.string().max(INPUT_FILE_NAME_MAX_LENGTH),
        sizeBytes: z.number().int().min(0),
        rowCount: z.number().int().min(0),
      })
      .strict()
      .nullable(),
    /** Nextflow runs only; `null` for Smart Checkup. */
    run: jobRunInfoSchema.nullable(),
    /** Output manifest totals of a COMPLETED Nextflow run, otherwise `null`. */
    outputs: jobOutputsSummarySchema.nullable(),
    cancellable: z.boolean(),
    history: z.array(jobStatusHistoryItemSchema),
    failureSummary: z.string().max(SUMMARY_MAX_LENGTH).nullable(),
    statusUrl: z.string().min(1),
  })
  .strict();

export const jobSubmitResponseSchema = z
  .object({
    job: jobSummarySchema,
    statusUrl: z.string().min(1),
  })
  .strict();

export const jobCancelResponseSchema = z
  .object({
    job: jobSummarySchema,
  })
  .strict();

export const jobListSchema = z
  .object({
    items: z.array(jobSummarySchema).max(JOB_PAGE_SIZE_MAX),
    page: z.number().int().min(1),
    limit: z.number().int().min(1).max(JOB_PAGE_SIZE_MAX),
    total: z.number().int().min(0),
  })
  .strict();

export const sampleInputSchema = z
  .object({
    parameters: jobParametersSchema,
    file: jobInputFileSchema,
    format: z
      .object({
        header: z.literal(INPUT_FILE_HEADER),
        maxBytes: z.literal(INPUT_FILE_MAX_BYTES),
        maxRows: z.literal(INPUT_FILE_MAX_ROWS),
        markers: z.array(
          z
            .object({
              marker: inputMarkerNameSchema,
              unit: z.string(),
              min: z.number(),
              max: z.number(),
            })
            .strict(),
        ),
      })
      .strict(),
  })
  .strict();
