import { z } from 'zod';

import {
  INPUT_FILE_MAX_ROWS,
  LIFESTYLE_FACTORS,
  NO_MOCK_RECOMMENDATION_RULE_ID,
  RESULT_ARTIFACT_KINDS,
  RUN_INPUT_RELATIVE_PATH_MAX_LENGTH,
  RUN_NAME_MAX_LENGTH,
  TRAINING_BANDS,
} from '../constants.js';
import {
  ageBandSchema,
  focusAreaSchema,
  inputMarkerNameSchema,
  lifestyleFactorSchema,
} from './jobs.js';

/** Upper bound of files listed for one job (matches the API output manifest limit). */
const ARTIFACTS_MAX = 1000;
/** Upper bound of per-sample rows (matches the stats parser row limit, design C4). */
const SAMPLES_MAX = 1000;
const REFERENCES_MAX = 10;
const TEXT_MAX_LENGTH = 512;
const SHORT_TEXT_MAX_LENGTH = 256;

const isoDateTimeSchema = z.iso.datetime({ offset: true });
const countSchema = z.number().int().min(0);
const measureSchema = z.number().finite().min(0);

/** Cuid identifiers generated by Prisma; anything else is treated as an unknown artifact. */
export const artifactIdSchema = z.string().regex(/^[a-z0-9]{20,40}$/);
export const resultArtifactKindSchema = z.enum(RESULT_ARTIFACT_KINDS);
export const resultArtifactCategorySchema = z.enum(['RESULT', 'READS', 'STATS', 'REPORT', 'OTHER']);
export const trainingBandSchema = z.enum(TRAINING_BANDS);

export const resultArtifactSchema = z
  .object({
    id: artifactIdSchema,
    kind: resultArtifactKindSchema,
    category: resultArtifactCategorySchema,
    /** Path relative to the job's output (or the generated file name); never an absolute path. */
    displayName: z.string().min(1).max(RUN_INPUT_RELATIVE_PATH_MAX_LENGTH),
    sizeBytes: countSchema,
    contentType: z.string().min(1).max(128),
    /** `true` only for allowlisted HTML reports shown in the sandboxed viewer (design C6). */
    viewable: z.boolean(),
    viewNote: z.string().min(1).max(SHORT_TEXT_MAX_LENGTH).nullable(),
  })
  .strict();

/** In-app path (`/help#results`) or an external `https://` documentation link. */
export const resultReferenceSchema = z
  .object({
    label: z.string().min(1).max(128),
    href: z
      .string()
      .min(1)
      .max(SHORT_TEXT_MAX_LENGTH)
      .refine(
        (value) => /^\/(?!\/)/.test(value) || /^https:\/\/[^\s/]+(\/\S*)?$/.test(value),
        'Use an in-app path or an https URL.',
      ),
  })
  .strict();

/** Factor that made a mock rule match, e.g. `focusArea:LIVER`, `marker:alt`. */
const matchedFactorSchema = z.string().regex(/^(focusArea|marker|lifestyle):[A-Za-z0-9_]{1,64}$/);

export const recommendationSchema = z
  .object({
    ruleId: z.string().regex(/^[A-Z0-9_-]{1,64}$/),
    ruleVersion: z.string().min(1).max(64),
    packageLabel: z.string().min(1).max(128),
    reason: z.string().min(1).max(TEXT_MAX_LENGTH),
    matchedFactors: z
      .array(matchedFactorSchema)
      .max(INPUT_FILE_MAX_ROWS + LIFESTYLE_FACTORS.length + 1),
    matched: z.boolean(),
    disclaimer: z.string().min(1).max(SHORT_TEXT_MAX_LENGTH),
  })
  .strict()
  .refine(
    (value) => value.matched === (value.ruleId !== NO_MOCK_RECOMMENDATION_RULE_ID),
    'Only NO_MATCH may be an unmatched recommendation.',
  )
  .refine(
    (value) => value.matched || value.matchedFactors.length === 0,
    'An unmatched recommendation has no matched factors.',
  );

export const smartCheckupResultSchema = z
  .object({
    pipelineId: z.literal('smart-checkup'),
    summary: z
      .object({
        runName: z.string().max(RUN_NAME_MAX_LENGTH),
        focusArea: focusAreaSchema,
        ageBand: ageBandSchema,
        lifestyleFactors: z.array(lifestyleFactorSchema).max(LIFESTYLE_FACTORS.length),
        markerCount: countSchema.max(INPUT_FILE_MAX_ROWS),
        generatedAt: isoDateTimeSchema,
      })
      .strict(),
    markers: z
      .array(
        z
          .object({
            marker: inputMarkerNameSchema,
            value: z.number().finite(),
            unit: z.string().min(1).max(32),
            min: z.number().finite(),
            max: z.number().finite(),
            midpoint: z.number().finite(),
            band: trainingBandSchema,
          })
          .strict(),
      )
      .max(INPUT_FILE_MAX_ROWS),
    recommendation: recommendationSchema,
    artifacts: z.array(resultArtifactSchema).max(ARTIFACTS_MAX),
    references: z.array(resultReferenceSchema).max(REFERENCES_MAX),
  })
  .strict();

export const nextflowResultSchema = z
  .object({
    pipelineId: z.literal('wf-renamefastq'),
    summary: z
      .object({
        runName: z.string().max(RUN_NAME_MAX_LENGTH),
        sampleCount: countSchema,
        totalReads: countSchema,
        totalBases: countSchema,
        outputFileCount: countSchema,
        outputBytes: countSchema,
      })
      .strict(),
    samples: z
      .array(
        z
          .object({
            sample: z.string().min(1).max(RUN_INPUT_RELATIVE_PATH_MAX_LENGTH),
            numSeqs: countSchema,
            sumLen: countSchema,
            minLen: countSchema,
            avgLen: measureSchema,
            maxLen: countSchema,
            avgQual: measureSchema,
          })
          .strict(),
      )
      .max(SAMPLES_MAX),
    artifacts: z.array(resultArtifactSchema).max(ARTIFACTS_MAX),
    references: z.array(resultReferenceSchema).max(REFERENCES_MAX),
  })
  .strict();

/** `GET /jobs/{jobId}/result` payload, one shape per pipeline. */
export const jobResultSchema = z.discriminatedUnion('pipelineId', [
  smartCheckupResultSchema,
  nextflowResultSchema,
]);
