#!/usr/bin/env bash
# One-time host-run setup so this machine can run wf-renamefastq (pipeline-catalog-nextflow design,
# Add-on — Team host-run setup). Run from anywhere inside the repository, online:
#   scripts/setup-nextflow.sh            # create .env.host, build, download pipeline assets, check
#   scripts/setup-nextflow.sh --force    # also rewrite an existing .env.host (old one kept as .bak)
# Optional: PORTAL_DATA_ROOT=/path (default ~/portal-data) — must be a folder Docker can share.
# Requires a working Docker Compose setup first (.env with SESSION_SECRET and ENCRYPTED_DATA_ROOT).
set -euo pipefail

FORCE=false
case "${1:-}" in
  '') ;;
  --force) FORCE=true ;;
  *) echo "Usage: $0 [--force]" >&2; exit 2 ;;
esac

REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO_DIR"
DATA_PARENT="${PORTAL_DATA_ROOT:-$HOME/portal-data}"

step() { printf '\n==> %s\n' "$*"; }
fail() { printf 'setup-nextflow: %s\n' "$*" >&2; exit 1; }

# Reads KEY from .env without executing the file; never prints the value.
env_value() { grep -E "^$1=" .env | tail -n 1 | cut -d= -f2- || true; }

# ---------- 1. Tools ----------
step "Checking tools"
command -v node >/dev/null || fail "Node.js 24 is required (see .node-version)"
[[ "$(node -p 'process.versions.node.split(".")[0]')" == "24" ]] || fail "Node.js 24 is required, found $(node -v)"
command -v corepack >/dev/null || fail "corepack is required (ships with Node.js)"
corepack enable >/dev/null 2>&1 || true
DOCKER_PATH="$(command -v docker || true)"
[[ -n "$DOCKER_PATH" ]] || fail "Docker is required (Docker Desktop on macOS, Docker Engine on Linux)"
"$DOCKER_PATH" info >/dev/null 2>&1 || fail "Docker is installed but not running"
NEXTFLOW_PATH="$(command -v nextflow || true)"
if [[ -z "$NEXTFLOW_PATH" ]]; then
  fail "Nextflow is required. macOS: brew install openjdk@25 nextflow — Linux: https://www.nextflow.io/docs/latest/install.html"
fi
NEXTFLOW_VERSION="$("$NEXTFLOW_PATH" -version 2>/dev/null | awk '/version/ {print $2; exit}' || true)"
[[ -n "$NEXTFLOW_VERSION" ]] || fail "nextflow -version failed (is Java installed?)"
echo "node $(node -v), docker $("$DOCKER_PATH" version --format '{{.Server.Version}}'), nextflow $NEXTFLOW_VERSION (tested: 26.10.2)"

# ---------- 2. Compose config this setup builds on ----------
[[ -f .env ]] || fail "missing .env — set up Docker Compose first (README.md, Quick start)"
SECRET_LENGTH="$(env_value SESSION_SECRET | tr -d '\n' | wc -c | tr -d ' ')"
[[ "$SECRET_LENGTH" -ge 32 ]] || fail "SESSION_SECRET in .env must be set (openssl rand -hex 48)"
COMPOSE_DATA="$(env_value ENCRYPTED_DATA_ROOT)"
[[ -n "$COMPOSE_DATA" ]] || fail "ENCRYPTED_DATA_ROOT is not set in .env"
[[ "$COMPOSE_DATA" == /* ]] || COMPOSE_DATA="$REPO_DIR/${COMPOSE_DATA#./}"
[[ -d "$COMPOSE_DATA" ]] || fail "ENCRYPTED_DATA_ROOT folder $COMPOSE_DATA does not exist"

# ---------- 3. Data folders ----------
step "Preparing $DATA_PARENT"
mkdir -p "$DATA_PARENT/storage" "$DATA_PARENT/nxf-home"
chmod 700 "$DATA_PARENT" "$DATA_PARENT/storage" "$DATA_PARENT/nxf-home"
if [[ -d "$COMPOSE_DATA/jobs" && ! -d "$DATA_PARENT/storage/jobs" ]]; then
  cp -Rp "$COMPOSE_DATA/jobs" "$DATA_PARENT/storage/"
  echo "copied existing job files from the Compose data folder"
fi

# ---------- 4. .env.host ----------
step "Writing .env.host"
if [[ -f .env.host && "$FORCE" != true ]]; then
  echo ".env.host already exists — kept (use --force to rewrite it)"
else
  [[ -f .env.host ]] && cp -p .env.host .env.host.bak
  (
    umask 077
    {
      echo "# Generated by scripts/setup-nextflow.sh from .env — host-run mode (gitignored, keep private)."
      grep -vE '^(DATABASE_URL|STORAGE_ROOT|ENCRYPTED_DATA_ROOT|NEXTFLOW_[A-Z_]+|DOCKER_BIN)=' .env \
        | grep -vE '^# *(Pipeline Catalog|STORAGE_ROOT must|Executables resolved|Optional absolute|Concurrent Nextflow|Per-run caps|Wait after SIGTERM|How often pipeline)'
      echo "DATABASE_URL=file:$COMPOSE_DATA/portal.db"
      echo "STORAGE_ROOT=$DATA_PARENT/storage"
      echo "NEXTFLOW_ENABLED=true"
      echo "NEXTFLOW_HOME=$DATA_PARENT/nxf-home"
      echo "NEXTFLOW_BIN=$NEXTFLOW_PATH"
      echo "DOCKER_BIN=$DOCKER_PATH"
      echo "NEXTFLOW_MAX_CONCURRENT_RUNS=1"
    } > .env.host
  )
  chmod 600 .env.host
  echo ".env.host written (mode 600; SESSION_SECRET copied from .env, not printed)"
fi

# ---------- 5. Build and database ----------
step "Installing and building (pnpm)"
pnpm install --frozen-lockfile
pnpm --filter @portal/shared build
DATABASE_URL="file:$COMPOSE_DATA/portal.db" pnpm --filter @portal/api prisma:generate
pnpm --filter @portal/api build
pnpm --filter @portal/web build
DATABASE_URL="file:$COMPOSE_DATA/portal.db" pnpm exec prisma migrate deploy

# ---------- 6. Pipeline assets (online once) and offline check ----------
step "Downloading the pinned pipeline, plugin and images (online, once)"
node --env-file=.env.host apps/api/dist/cli/pipelines.js pipelines:setup
step "Checking readiness (offline)"
node --env-file=.env.host apps/api/dist/cli/pipelines.js pipelines:check

cat <<'EOF'

==> Done. Start host-run mode (wf-renamefastq available) from the repository root:

  docker compose stop api
  API_UPSTREAM=host.docker.internal:3000 docker compose up -d --no-deps --force-recreate caddy
  node --env-file=.env.host apps/api/dist/main.js

Back to Compose mode (Smart Checkup only): stop the node process, then
  docker compose up -d --force-recreate api caddy

The host API listens on all interfaces (port 3000): use a trusted network with the firewall on.
Test or public FASTQ only (no patient data), at most 1 GB and 10 files per run.
EOF
